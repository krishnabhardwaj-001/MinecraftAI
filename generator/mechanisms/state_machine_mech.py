import json
import re
from typing import Any, Dict, List, Optional

from generator.mechanisms.base import BaseMechanismGenerator
from generator.mechanisms.function_mech import FunctionMechanismGenerator
from generator.models import ActionSpecification, DatapackResource, MechanismSpecification


class StateMachineMechanismGenerator(BaseMechanismGenerator):
    """
    Deterministic mechanism generator for edge-triggered and stateful transitions
    in Minecraft Java 1.21.11.

    Generates:
    - data/<namespace>/function/load.mcfunction (scoreboard objective setup + #global initialization)
    - data/<namespace>/function/tick.mcfunction (action check -> state latch -> reset)
    - data/minecraft/tags/function/load.json (#minecraft:load tag)
    - data/minecraft/tags/function/tick.json (#minecraft:tick tag)
    """

    def __init__(self, version: str = "1.21.11"):
        self.version = version
        self.func_gen = FunctionMechanismGenerator(version=version)

    def _normalize_id(self, raw_id: Optional[str], default_prefix: str = "minecraft:") -> str:
        if not raw_id:
            return ""
        clean = str(raw_id).strip()
        if not clean:
            return clean
        if clean.startswith("#"):
            tag_name = clean[1:].strip()
            if ":" not in tag_name:
                return f"#{default_prefix}{tag_name}"
            return f"#{tag_name}"
        if ":" not in clean:
            return f"{default_prefix}{clean}"
        return clean

    def _extract_action_command(self, action: ActionSpecification) -> str:
        """
        Synthesizes the core action command suitable for execution after
        context has already been anchored with 'as @a at @s'.
        """
        raw_cmd = self.func_gen.synthesize_action(action)
        if not raw_cmd:
            return "say action triggered"

        # If already wrapped with 'execute as ... at @s run <cmd>', strip to inner command
        m = re.search(r"^execute\s+as\s+\S+\s+at\s+@s\s+run\s+(.+)$", raw_cmd)
        if m:
            return m.group(1).strip()

        # If wrapped with 'execute ... run <cmd>', strip
        m2 = re.search(r"^execute\s+.*?run\s+(.+)$", raw_cmd)
        if m2:
            return m2.group(1).strip()

        # If targeting @a directly (e.g. give @a ...), convert to @s since context is 'as @a'
        if raw_cmd.startswith("give @a "):
            return f"give @s {raw_cmd[8:]}"
        if raw_cmd.startswith("effect give @a "):
            return f"effect give @s {raw_cmd[15:]}"

        return raw_cmd

    def generate(self, spec: MechanismSpecification) -> List[DatapackResource]:
        resources: List[DatapackResource] = []
        ns = spec.namespace or "minecraft_ai"

        obj_name = (spec.objective or spec.path or "event_state").strip()
        cond_pred = self._normalize_id(spec.condition_predicate or "minecraft_ai:is_raining", default_prefix="minecraft_ai:")
        scope = str(spec.state_scope or "global").strip().lower()

        # Parse on_enter and on_exit actions
        on_enter_actions: List[ActionSpecification] = []
        for a in (spec.on_enter or spec.actions or []):
            if isinstance(a, ActionSpecification):
                on_enter_actions.append(a)
            elif isinstance(a, dict):
                on_enter_actions.append(ActionSpecification(**a))

        on_exit_actions: List[ActionSpecification] = []
        for a in (spec.on_exit or []):
            if isinstance(a, ActionSpecification):
                on_exit_actions.append(a)
            elif isinstance(a, dict):
                on_exit_actions.append(ActionSpecification(**a))

        # Default action fallback if none specified
        if not on_enter_actions:
            on_enter_actions.append(
                ActionSpecification(
                    action_type="give_item",
                    target="@a",
                    item="minecraft:diamond",
                    count=1
                )
            )

        # -------------------------------------------------------------
        # 1. Generate load.mcfunction
        # -------------------------------------------------------------
        load_lines: List[str] = [
            "# Generated by MinecraftAI - State Machine Initialization",
            f"scoreboard objectives add {obj_name} dummy"
        ]
        if scope == "global":
            load_lines.append(f"scoreboard players set #global {obj_name} 0")

        # Diagnostic tracking & reload announcement
        load_lines.append("scoreboard objectives add mcai_debug dummy")
        load_lines.append("scoreboard players set #load_ran mcai_debug 1")
        load_lines.append("scoreboard players set #tick_count mcai_debug 0")
        load_lines.append(f"say [MinecraftAI] [LOAD OK] minecraft:load called {ns}:load.mcfunction")

        load_content = "\n".join(load_lines) + "\n"
        resources.append(
            DatapackResource(
                relative_path=f"data/{ns}/function/load.mcfunction",
                content=load_content,
                resource_type="function"
            )
        )

        # -------------------------------------------------------------
        # 2. Generate tick.mcfunction
        # -------------------------------------------------------------
        tick_lines: List[str] = [
            "# Generated by MinecraftAI - State Machine Tick Handler",
            "scoreboard players add #tick_count mcai_debug 1",
            f"execute if score #tick_count mcai_debug matches 1 run say [MinecraftAI] [TICK OK] minecraft:tick registered & running {ns}:tick.mcfunction"
        ]

        if scope == "global":
            # Rule 24: Global State Machine
            # 1. Action check: if score matches 0 and condition is met -> execute action
            for act in on_enter_actions:
                act_cmd = self._extract_action_command(act)
                tick_lines.append(
                    f"execute if score #global {obj_name} matches 0 if predicate {cond_pred} run say [MinecraftAI] [EVENT] Condition {cond_pred} met. Executing on_enter action(s)."
                )
                tick_lines.append(
                    f"execute if score #global {obj_name} matches 0 if predicate {cond_pred} as @a at @s run {act_cmd}"
                )

            # 2. On exit actions (if any)
            for act in on_exit_actions:
                act_cmd = self._extract_action_command(act)
                tick_lines.append(
                    f"execute if score #global {obj_name} matches 1 unless predicate {cond_pred} as @a at @s run {act_cmd}"
                )

            # 3. Latch state to 1 when predicate is active
            tick_lines.append(
                f"execute if predicate {cond_pred} run scoreboard players set #global {obj_name} 1"
            )

            # 4. Reset state to 0 when predicate ceases
            tick_lines.append(
                f"execute unless predicate {cond_pred} run scoreboard players set #global {obj_name} 0"
            )

        else:
            # Per-player State Machine
            # 1. Safely initialize joining players dynamically on tick
            tick_lines.append(
                f"execute as @a unless score @s {obj_name} matches 0..1 run scoreboard players set @s {obj_name} 0"
            )

            # 2. Action check
            for act in on_enter_actions:
                act_cmd = self._extract_action_command(act)
                tick_lines.append(
                    f"execute as @a at @s if score @s {obj_name} matches 0 if predicate {cond_pred} run {act_cmd}"
                )

            # 3. On exit actions (if any)
            for act in on_exit_actions:
                act_cmd = self._extract_action_command(act)
                tick_lines.append(
                    f"execute as @a at @s if score @s {obj_name} matches 1 unless predicate {cond_pred} run {act_cmd}"
                )

            # 4. Latch per-player state to 1
            tick_lines.append(
                f"execute as @a if predicate {cond_pred} run scoreboard players set @s {obj_name} 1"
            )

            # 5. Reset per-player state to 0
            tick_lines.append(
                f"execute as @a unless predicate {cond_pred} run scoreboard players set @s {obj_name} 0"
            )

        tick_content = "\n".join(tick_lines) + "\n"
        resources.append(
            DatapackResource(
                relative_path=f"data/{ns}/function/tick.mcfunction",
                content=tick_content,
                resource_type="function"
            )
        )

        # -------------------------------------------------------------
        # 3. Generate diagnostic debug.mcfunction
        # -------------------------------------------------------------
        debug_lines = [
            "# Generated by MinecraftAI - Diagnostic Inspection",
            "say ========================================",
            "say [MinecraftAI Diagnostic Report]",
            f"say Datapack: {ns} | Target: {ns}:tick.mcfunction",
            "say Tag Expected: data/minecraft/tags/function/tick.json",
            "say ----------------------------------------",
            f"execute if score #load_ran mcai_debug matches 1 run say [1] minecraft:load: SUCCESS ({ns}:load.mcfunction executed)",
            f"execute unless score #load_ran mcai_debug matches 1 run say [1] minecraft:load: NOT EXECUTED (Check datapack enabled and tags/function/load.json)",
            f"execute if score #tick_count mcai_debug matches 1.. run say [2] minecraft:tick: SUCCESS ({ns}:tick.mcfunction is actively ticking)",
            f"execute if score #tick_count mcai_debug matches 0 run say [2] minecraft:tick: NOT RUNNING! FAILURE IN TICK REGISTRATION / TAG ({ns}:tick internal logic is NOT at fault; data/minecraft/tags/function/tick.json did not load or reference this function)",
            f"execute if score #global {obj_name} matches 0 run say [3] State Machine: IDLE (#global {obj_name} = 0, waiting for condition)",
            f"execute if score #global {obj_name} matches 1 run say [3] State Machine: ACTIVE (#global {obj_name} = 1, condition active / action triggered)",
            "say ========================================"
        ]
        debug_content = "\n".join(debug_lines) + "\n"
        resources.append(
            DatapackResource(
                relative_path=f"data/{ns}/function/debug.mcfunction",
                content=debug_content,
                resource_type="function"
            )
        )

        # -------------------------------------------------------------
        # 4. Generate function tags: load.json and tick.json (minimal canonical format)
        # -------------------------------------------------------------
        load_tag_json = json.dumps({"values": [f"{ns}:load"]}, indent=2) + "\n"
        resources.append(
            DatapackResource(
                relative_path="data/minecraft/tags/function/load.json",
                content=load_tag_json,
                resource_type="function_tag"
            )
        )

        tick_tag_json = json.dumps({"values": [f"{ns}:tick"]}, indent=2) + "\n"
        resources.append(
            DatapackResource(
                relative_path="data/minecraft/tags/function/tick.json",
                content=tick_tag_json,
                resource_type="function_tag"
            )
        )

        return resources

from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field

from generator.models import GenerationResult
from repair.models import RepairResult
from validator.models import ValidationResult


from qa.models import IntentVerificationResult, QAResult
from qa.runtime import RuntimeTestResult


class PipelineStage(str, Enum):
    UNDERSTANDING = "understanding"
    RETRIEVAL = "retrieval"
    PLANNING = "planning"
    GENERATION = "generation"
    VALIDATION = "validation"
    QA_REVIEW = "qa_review"
    INTENT_VERIFICATION = "intent_verification"
    FINAL_VERIFICATION = "final_verification"
    REPAIR = "repair"
    COMPLETED = "completed"


class PipelineResult(BaseModel):
    """
    Typed result of the complete MinecraftAI end-to-end pipeline execution.
    """
    model_config = ConfigDict(extra="allow")

    status: str = Field(
        ...,
        description="'verified', 'success', 'needs_clarification', 'failed', 'qa_failed', 'verification_failed', or 'error'"
    )
    minecraft_version: str = Field(
        default="1.21.11",
        description="Target Minecraft Java Edition version"
    )
    original_request: str = Field(
        ...,
        description="Original natural-language request from the user"
    )

    # Stage artifacts
    understanding: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured understanding result from AI understanding layer"
    )
    context: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Retrieved Minecraft knowledge context (RAG)"
    )
    plan: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Implementation plan generated by the AI planner"
    )
    generation: Optional[GenerationResult] = Field(
        default=None,
        description="Datapack files and paths produced by the deterministic generator"
    )
    validation: Optional[ValidationResult] = Field(
        default=None,
        description="Validation checks and issues from the deterministic validator"
    )
    repair: Optional[RepairResult] = Field(
        default=None,
        description="Diagnostic repair history if validation triggered the AI repair loop"
    )
    qa_result: Optional[QAResult] = Field(
        default=None,
        description="Autonomous QA review outcome and structured findings"
    )
    intent_verification: Optional[IntentVerificationResult] = Field(
        default=None,
        description="Comparison outcome against original user intent"
    )
    runtime_result: Optional[RuntimeTestResult] = Field(
        default=None,
        description="Runtime simulation or server test outcome"
    )
    verification_status: Optional[str] = Field(
        default=None,
        description="'verified', 'verification_failed', 'structurally_valid', or 'qa_failed'"
    )
    message: Optional[str] = Field(
        default=None,
        description="Human-readable outcome summary"
    )

    # Outcomes
    final_datapack_path: Optional[str] = Field(
        default=None,
        description="Absolute filesystem path to the final validated datapack directory"
    )
    final_zip_path: Optional[str] = Field(
        default=None,
        description="Absolute filesystem path to the final validated datapack ZIP archive"
    )
    clarification: Optional[str] = Field(
        default=None,
        description="Clarification reason/question if the request was ambiguous"
    )
    clarification_requirements: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Structured clarification requirement items if clarification was required"
    )
    error_code: Optional[str] = Field(
        default=None,
        description="Structured error code (e.g. 'provider_unreachable', 'provider_auth', 'validation_failed')"
    )
    failed_stage: Optional[str] = Field(
        default=None,
        description="Identifier of the pipeline stage that failed (e.g. 'understanding', 'planning', 'generation', etc.)"
    )
    diagnostic: Optional[str] = Field(
        default=None,
        description="Actionable diagnostic message for troubleshooting"
    )
    errors: List[str] = Field(
        default_factory=list,
        description="List of error messages if the pipeline failed or encountered exceptions"
    )
    execution_summary: str = Field(
        default="",
        description="Stage-by-stage execution trace and outcome summary"
    )

    @property
    def is_success(self) -> bool:
        return self.status in ("success", "verified") and self.final_datapack_path is not None

    def summary(self) -> str:
        lines = [
            f"Pipeline Status: {self.status.upper()}",
            f"Version: Java {self.minecraft_version}",
            f"Request: \"{self.original_request}\"",
        ]
        if self.clarification:
            lines.append(f"Clarification Required: {self.clarification}")
        if self.final_datapack_path:
            lines.append(f"Datapack Directory: {self.final_datapack_path}")
        if self.final_zip_path:
            lines.append(f"Datapack ZIP: {self.final_zip_path}")
        if self.repair and self.repair.attempts:
            lines.append(f"Repairs: {len(self.repair.attempts)} attempt(s) ({self.repair.status})")
        if self.errors:
            lines.append("Errors:")
            for err in self.errors:
                lines.append(f"  - {err}")
        return "\n".join(lines)
